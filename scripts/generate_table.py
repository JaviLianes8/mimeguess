"""Generate the embedded MIME table from the committed mime-db snapshot.

Usage:
    python scripts/generate_table.py           # rewrite the generated files
    python scripts/generate_table.py --check   # exit 1 if they are out of date

Inputs (committed):
    data/mime-db-1.54.0.json.gz   gzip of db.json exactly as fetched from SOURCE_URL
    scripts/_supplement.py        small hand-written additions, see that file
    scripts/_score.py             conflict scoring ported from mime-types 3.0.2

Outputs (committed, do not edit by hand):
    src/mimeguess/_data.json.gz   the table the package loads at run time
    src/mimeguess/_meta.py        provenance constants
"""

from __future__ import annotations

import gzip
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _score import preferred
from _supplement import EXTRA_EXTENSIONS, PREFERRED_EXTENSION

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "data" / "mime-db-1.54.0.json.gz"
OUT_DATA = ROOT / "src" / "mimeguess" / "_data.json.gz"
OUT_META = ROOT / "src" / "mimeguess" / "_meta.py"

SOURCE_NAME = "mime-db"
SOURCE_VERSION = "1.54.0"
SOURCE_URL = "https://raw.githubusercontent.com/jshttp/mime-db/v1.54.0/db.json"
SOURCE_RETRIEVED = "2026-10-12"
SOURCE_LICENSE = "MIT"

Row = list[Any]  # [source, charset, compressible, [extensions]]


def snapshot_bytes() -> bytes:
    """Return db.json exactly as it was fetched."""
    return gzip.decompress(SNAPSHOT.read_bytes())


def build(db: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """Turn a mime-db mapping into the package table."""
    types: dict[str, Row] = {}
    for mime, entry in db.items():
        types[mime] = [
            entry.get("source", "mime-db"),
            entry.get("charset"),
            entry.get("compressible"),
            list(entry.get("extensions", [])),
        ]
    order = list(db)
    for mime, extra in EXTRA_EXTENSIONS.items():
        if mime not in types:
            types[mime] = ["supplement", None, None, []]
            order.append(mime)
        exts = types[mime][3]
        exts.extend(ext for ext in extra if ext not in exts)
    for mime, ext in PREFERRED_EXTENSION.items():
        exts = types[mime][3]
        if ext not in exts:
            raise ValueError(f"{ext!r} is not listed for {mime!r}")
        exts.remove(ext)
        exts.insert(0, ext)
    # Scoring uses mime-db's own source field; types it leaves unsourced, and
    # supplement-only types, score as "no source" just like in mime-types.
    sources = {mime: db.get(mime, {}).get("source") for mime in types}
    extensions: dict[str, str] = {}
    for mime in order:
        for ext in types[mime][3]:
            extensions[ext] = preferred(extensions.get(ext), mime, sources)
    return {"types": types, "extensions": extensions}


def render_data(table: dict[str, Any]) -> bytes:
    """Serialise the table deterministically (uncompressed JSON)."""
    text = json.dumps(table, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return text.encode("ascii")


def render_meta(raw: bytes, table: dict[str, Any]) -> str:
    """Render the provenance module."""
    sha = hashlib.sha256(raw).hexdigest()
    lines = [
        '"""Provenance of the embedded table.',
        "",
        "Generated by scripts/generate_table.py from data/mime-db-1.54.0.json.gz.",
        "Do not edit by hand.",
        '"""',
        "",
        f"NAME = {SOURCE_NAME!r}",
        f"VERSION = {SOURCE_VERSION!r}",
        f"URL = {SOURCE_URL!r}",
        f"SHA256 = {sha!r}",
        f"RETRIEVED = {SOURCE_RETRIEVED!r}",
        f"LICENSE = {SOURCE_LICENSE!r}",
        f"TYPE_COUNT = {len(table['types'])}",
        f"EXTENSION_COUNT = {len(table['extensions'])}",
        "",
    ]
    return "\n".join(lines).replace("'", '"')


def generate() -> tuple[bytes, str]:
    """Return the expected (uncompressed data, meta source) from the snapshot."""
    raw = snapshot_bytes()
    table = build(json.loads(raw))
    return render_data(table), render_meta(raw, table)


def main(argv: list[str]) -> int:
    data, meta = generate()
    if "--check" in argv:
        current = gzip.decompress(OUT_DATA.read_bytes()) if OUT_DATA.exists() else b""
        meta_now = OUT_META.read_text(encoding="utf-8") if OUT_META.exists() else ""
        if current != data or meta_now != meta:
            print("generated table is out of date; run scripts/generate_table.py")
            return 1
        print("generated table is up to date")
        return 0
    OUT_DATA.write_bytes(gzip.compress(data, compresslevel=9, mtime=0))
    OUT_META.write_text(meta, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_DATA.name} and {OUT_META.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
